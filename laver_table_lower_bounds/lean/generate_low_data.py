"""Generate kernel-checkable A_9 product proofs from the row recurrence.

This script is only a proof-term generator. Its output must pass Lean before
any result is trusted. It neither constructs a large Laver table nor uses
native_decide. Resource limits: 10 seconds, 100,000 distinct products.
"""
from pathlib import Path
from time import monotonic
import json
root = Path(__file__).resolve().parent
deadline = monotonic() + 10
size = 512
values = {}
order = []
proofs = {}
periods = {}
last_known = {}


def evaluate(a, b):
    target = a, b
    pending = [target]
    while pending:
        if monotonic() > deadline or len(values) > 100000 or len(pending) > 2000:
            raise RuntimeError("proof-generator resource limit")
        a, b = key = pending[-1]
        if key in values:
            pending.pop()
            continue
        kind = "base"
        if a == 0:
            value = b % size
        elif b == 0:
            value = 0
        elif b == 1:
            value = (a + 1) % size
        elif a in periods and b >= periods[a]:
            period = periods[a]
            dependency = a, b % period
            if dependency not in values:
                pending.append(dependency)
                continue
            value = values[dependency]
            kind = "period", period
        elif last_known.get(a, 0) + 1 < b:
            pending.append((a, last_known.get(a, 0) + 1))
            continue
        else:
            previous = values[a, b - 1]
            dependency = previous, a + 1
            if dependency not in values:
                pending.append(dependency)
                continue
            value = values[dependency]
            kind = "recurrence"
        values[key] = value
        proofs[key] = kind
        order.append(key)
        if b == last_known.get(a, 0) + 1:
            last_known[a] = b
        if value == 0 and b > 0:
            periods.setdefault(a, b)
        pending.pop()
    return values[target]


point_inputs = {
    1: [0, 1, 2, 3, 4], 2: [1, 2], 3: [0, 1, 2],
    4: [2, 3], 5: [0, 1], 6: [1], 7: [0, 1, 2],
    8: [0, 1, 2, 3], 9: [0, 1], 10: [0, 1],
    11: [0, 1], 12: [2],
}
targets = [(a, 1 << x) for a, xs in point_inputs.items() for x in xs]
for target in targets:
    evaluate(*target)

report = {
    "size": size,
    "products": len(order),
    "largest_input": max(max(a, b) for a, b in order),
    "targets": [{"a": a, "b": b, "value": values[a, b]} for a, b in targets],
    "status": "generated, not yet kernel checked",
}
(root / "low-data-generation.json").write_text(
    json.dumps(report, indent=2), encoding="utf-8")

header = [
    "/- Generated by generate_low_data.py. Every equality is proved from the",
    "row recurrence and kernel-checked numeral reduction; no native_decide. -/",
    "set_option autoImplicit false", "set_option maxHeartbeats 2000000", "",
    "namespace LaverLowerBounds.FiniteTable.LowProducts", "",
    "variable (T : FiniteTable 512)", "",
]
fragments = []
for a, b in order:
    lines = []
    value = values[a, b]
    name = f"v{a}_{b}"
    lines.append(f"theorem {name} : T.mul {a} {b} = {value} := by")
    if a == 0:
        lines.append(f"  simpa using T.zero_mul {b}")
    elif b == 0:
        lines.append(f"  exact T.mul_zero {a}")
    elif b == 1:
        lines.append(f"  simpa using T.mul_one {a}")
    elif isinstance(proofs[a, b], tuple):
        period = proofs[a, b][1]
        lines.extend([
            f"  rw [T.reduce_period (v{a}_{period} T) {b}]",
            f"  exact v{a}_{b % period} T",
        ])
    else:
        previous = values[a, b - 1]
        lines.extend([
            f"  rw [T.row_recurrence {a} {b - 1}, v{a}_{b - 1} T]",
            f"  exact v{previous}_{a + 1} T",
        ])
    lines.append("")
    fragments.append(lines)
batch_dir = root / "LaverLowerBounds" / "LowProducts"
batch_dir.mkdir(exist_ok=True)
modules = []
for start in range(0, len(fragments), 200):
    batch = start // 200
    module = f"LaverLowerBounds/LowProducts/Part{batch:03}"
    prior = "LaverLowerBounds.FiniteCapped" if batch == 0 else (
        f"LaverLowerBounds.LowProducts.Part{batch - 1:03}")
    lines = [f"import {prior}", ""] + header
    for fragment in fragments[start:start + 200]:
        lines.extend(fragment)
    lines.append("end LaverLowerBounds.FiniteTable.LowProducts")
    (root / (module + ".lean")).write_text("\n".join(lines) + "\n", encoding="utf-8")
    modules.append(module)
lines = [f"import {modules[-1].replace('/', '.')}", "",
         "namespace LaverLowerBounds.FiniteTable.LowProducts", ""]
for a, b in targets:
    lines.append(f"#print axioms v{a}_{b}")
lines.extend(["", "end LaverLowerBounds.FiniteTable.LowProducts", ""])
(root / "LaverLowerBounds" / "LowProducts.lean").write_text(
    "\n".join(lines), encoding="utf-8")
modules.append("LaverLowerBounds/LowProducts")
(root / "low-data-modules.txt").write_text("\n".join(modules) + "\n", encoding="utf-8")
print(json.dumps({"products": len(order), "modules": len(modules),
                  "elapsed_seconds": round(10 - (deadline - monotonic()), 3)}))
